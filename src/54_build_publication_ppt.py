def txbox(slide, x, y, w, h, text, size=14, bold=False, color=INK,
          align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP, italic=False, spacing=1.0):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = tf.margin_top = tf.margin_bottom = 0
    tf.vertical_anchor = anchor
    p = tf.paragraphs[0]
    p.alignment = align
    p.line_spacing = spacing
    r = p.add_run(); r.text = text
    f = r.font
    f.name, f.size, f.bold, f.italic, f.color.rgb = FONT, Pt(size), bold, italic, color
    return tb


def rect(slide, x, y, w, h, fill, line=None):
    from pptx.enum.shapes import MSO_SHAPE
    s = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y),
                               Inches(w), Inches(h))
    s.fill.solid(); s.fill.fore_color.rgb = fill
    if line is None:
        s.line.fill.background()
    else:
        s.line.color.rgb = line
    s.shadow.inherit = False
    return s


# ---------------------------------------------------------------- image fitting
def _row_ink(im):
    """Per-row 'has ink' mask, subsampled across the width for speed."""
    px = im.convert("L").load()
    w, h = im.size
    step = max(1, w // 300)
    return [any(px[x, y] < 205 for x in range(0, w, step)) for y in range(h)]


def strip_baked_title(path, strip=True):
    """Most archival figures carry their own 'Figure N | ...' banner, which would
    duplicate the slide header. Remove it when the top of the image is one or two
    thin text lines separated from the plot body by a clear white gap.

    Then trim the surrounding white border, so every figure fills its box with even
    margins instead of inheriting whatever padding matplotlib happened to leave.

    strip=False is used for the figures built by this script: they carry no banner, but
    they do carry a left-aligned 'A · ...' panel title in exactly the place a banner
    would sit, and losing that would silently delete a panel label.
    """
    im = Image.open(path).convert("RGB")
    w, h = im.size
    ink = _row_ink(im)
    if not any(ink):
        return path

    # ---- 1. drop a single leading title line, and only when it is unambiguous.
    # Exactly one line is removed: an earlier two-line version silently ate the first
    # bar of ranked bar charts, because a bar is also "a thin band then a gap".
    # The discriminator is that a title is followed by a gap AT LEAST as tall as the
    # text itself, whereas bars in a ranked chart sit closer together than they are thick.
    y0 = ink.index(True)
    if strip and y0 <= h * 0.05:
        y = y0
        while y < h and ink[y]:
            y += 1
        band = y - y0
        gap0 = y
        while y < h and not ink[y]:
            y += 1
        gap = y - gap0
        if 3 <= band <= h * 0.075 and gap >= band and gap0 + gap // 2 < h * 0.22:
            im = im.crop((0, gap0 + gap // 2, w, h))

    # ---- 2. trim the white frame so margins on the slide are even
    g = im.convert("L")
    bbox = g.point(lambda v: 255 if v < 246 else 0).getbbox()
    if bbox:
        pad = max(4, int(min(im.size) * 0.008))
        im = im.crop((max(0, bbox[0] - pad), max(0, bbox[1] - pad),
                      min(im.size[0], bbox[2] + pad), min(im.size[1], bbox[3] + pad)))

    p = os.path.join(TMP, "trim_" + os.path.basename(path))
    im.save(p)
    return p


def prepared(path, box_ar):
    """Return a path whose aspect ratio is usable inside a box of ratio box_ar.

    A figure much taller than the box (a long ranked bar chart) is cut into k
    equal-height panels laid left-to-right with a thin gutter. k is chosen so the
    reassembled image lands as close as possible to the box ratio, which is what
    makes those figures readable on a 16:9 slide instead of a 2-cm-wide strip.

    The threshold is deliberately severe. An earlier, looser one (anything narrower
    than 0.42 of the box ratio) sliced a SQUARE scatter plot down the middle and laid
    the two halves side by side, which destroys the figure rather than fitting it.
    Only a figure at least twice as tall as it is wide can be cut safely, because only
    a stacked/ranked chart has that shape; everything squarer goes to the TALL slide
    layout instead, where it keeps its full height next to a caption column.
    """
    im = Image.open(path).convert("RGB")
    w, h = im.size
    ar = w / h
    if ar >= 0.5:
        return path, ar
    k = max(2, min(4, round((box_ar / ar) ** 0.5)))
    band = h // k
    gut = max(12, w // 90)
    out = Image.new("RGB", (w * k + gut * (k - 1), band), "white")
    for i in range(k):
        out.paste(im.crop((0, i * band, w, (i + 1) * band)), (i * (w + gut), 0))
    p = os.path.join(TMP, f"split{k}_" + os.path.basename(path))
    out.save(p)
    return p, out.size[0] / out.size[1]


def place(slide, path, ar, x, y, w, h):
    """Fit-and-centre inside (x,y,w,h). Never crops, never overflows."""
    box_ar = w / h
    if ar >= box_ar:                              # width-limited
        dw, dh = w, w / ar
    else:                                         # height-limited
        dh, dw = h, h * ar
    slide.shapes.add_picture(path, Inches(x + (w - dw) / 2), Inches(y + (h - dh) / 2),
                             Inches(dw), Inches(dh))


# ---------------------------------------------------------------- slide makers
def new_deck():
    prs = Presentation()
    prs.slide_width, prs.slide_height = Inches(SW), Inches(SH)
    return prs


def blank(prs):
    return prs.slides.add_slide(prs.slide_layouts[6])


def footer(slide, n, tag):
    txbox(slide, M, FOOT_Y, SW - 2 * M - 0.8, FOOT_H,
          f"Human Plasma Immune Atlas   ·   {tag}", size=8.5, color=GREY,
          anchor=MSO_ANCHOR.MIDDLE)
    txbox(slide, SW - M - 0.8, FOOT_Y, 0.8, FOOT_H, str(n), size=8.5,
          color=GREY, align=PP_ALIGN.RIGHT, anchor=MSO_ANCHOR.MIDDLE)


def cap_size(text, area):
    """Point size that keeps the caption inside its band. area is in square inches."""
    for sz in (11.5, 11, 10.5, 10, 9.5, 9, 8.5, 8):
        # ~ characters that fit per square inch at this size, measured empirically
        if len(text) <= area * (150 * (10.0 / sz) ** 2):
            return sz
    return 7.5


def fig_slide(prs, n, tag, label, title, path, caption, subtitle=None):
    """Two layout modes, chosen from the figure's own aspect ratio, so that no slide
    is ever half empty:
      WIDE  (landscape figure)  -> figure spans the full width, caption underneath.
      TALL  (squarish or tall)  -> figure takes the full slide height on the left and
                                   the caption moves into a right-hand column.
    In both modes the zones are disjoint rectangles, so overlap is impossible."""
    s = blank(prs)
    rect(s, 0, 0, SW, 0.16, ACC)                              # top rule
    rect(s, M, BAND_Y + 0.04, 0.075, BAND_H - 0.08, ACC2)     # accent tick
    txbox(s, M + 0.20, BAND_Y, SW - 2 * M - 0.20, 0.40,
          f"{label}  |  {title}", size=19, bold=True, color=INK,
          anchor=MSO_ANCHOR.MIDDLE)
    if subtitle:
        txbox(s, M + 0.20, BAND_Y + 0.44, SW - 2 * M - 0.20, 0.38,
              subtitle, size=11.5, color=GREY, anchor=MSO_ANCHOR.MIDDLE)

    # slice very tall figures first, so the mode is chosen from what will actually
    # be drawn rather than from the raw file
    deck_native = os.path.basename(os.path.dirname(path)) == "deck"
    src, ar = prepared(strip_baked_title(path, strip=not deck_native), FIG_W / FIG_H)
    tall_h = FOOT_Y - 0.14 - FIG_Y                       # full remaining height

    if ar >= 1.85:                                       # ---- WIDE
        place(s, src, ar, FIG_X, FIG_Y, FIG_W, FIG_H)
        rect(s, M, CAP_Y, SW - 2 * M, 0.022, RGBColor(0xDD, 0xDD, 0xE0))
        cx, cy, cw, ch = M, CAP_Y + 0.10, SW - 2 * M, CAP_H - 0.10
    else:                                                # ---- TALL
        # split the width between figure and caption according to what the figure
        # actually needs at full height, so a near-square figure does not sit in a
        # wide box surrounded by dead space while the caption is squeezed.
        avail = SW - 2 * M - 0.34
        fw = min(avail - 2.95, max(avail - 4.65, tall_h * ar))
        cw = avail - fw
        place(s, src, ar, FIG_X, FIG_Y, fw, tall_h)
        cx = FIG_X + fw + 0.34
        cy, ch = FIG_Y, tall_h
        rect(s, cx, cy, 0.022, ch, RGBColor(0xDD, 0xDD, 0xE0))
        cx += 0.20; cw -= 0.20

    txbox(s, cx, cy, cw, ch, caption, size=cap_size(caption, cw * ch),
          color=RGBColor(0x33, 0x33, 0x33), spacing=1.10)
    footer(s, n, tag)
    return s


