"""
54 - Publication-level figure deck (PowerPoint)
==============================================
Lays every atlas figure onto a 16:9 widescreen slide using one fixed geometry, so
that across the whole deck the title band, the figure box and the caption band sit
at exactly the same coordinates on every slide.

Layout guarantees (this is the point of the script):
  * The three zones -- title band / figure box / caption band -- are disjoint
    rectangles. Nothing can overlap, because nothing is free-positioned.
  * Every figure is scaled to FIT its box with its aspect ratio preserved, then
    centred both ways, so margins are even on all four sides.
  * Figures far taller than the box (e.g. a 1636x8431 direction map) are sliced
    into equal vertical panels laid side by side, so they fill the box legibly
    instead of collapsing into an unreadable sliver.
  * Caption text is auto-shrunk to the caption band; it never spills into the
    figure box or off the slide.

Inputs : 08_figures/**/*.png  (already generated by src/26..53)
         09_tables/*.tsv, 06_genetic_causality/*.tsv  (for the live cover numbers)
Output : 08_figures/Human_Plasma_Immune_Atlas_Figures.pptx
         (plus a cardiovascular-only deck, Cardiovascular_Novelty_Figures.pptx)

Run:  python src/54_build_publication_ppt.py
"""
