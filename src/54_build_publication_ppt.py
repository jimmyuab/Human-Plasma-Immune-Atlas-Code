def _short(s, n):
    """Truncate at a word boundary with an ellipsis. Hard slicing produced labels like
    'Second line medication for Crohn's disea', which reads as a typo rather than a cut."""
    s = str(s)
    if len(s) <= n:
        return s
    cut = s[:n].rsplit(" ", 1)[0]
    return (cut if len(cut) >= n * 0.6 else s[:n]).rstrip(" ,;") + "…"


def _plural(n, word):
    return f"{n} {word}" + ("" if n == 1 else "s")


def _below(ax, ncol=3, size=7.4):
    """Legend parked under the axes. Inside the axes it collided with the bars on every
    ranked chart here, and 'best' just moved the collision around."""
    ax.legend(fontsize=size, ncol=ncol, loc="upper left",
              bbox_to_anchor=(0.0, -0.115), borderaxespad=0)


def _despine(ax, keep=("left", "bottom")):
    for s in ("top", "right", "left", "bottom"):
        if s not in keep:
            ax.spines[s].set_visible(False)


