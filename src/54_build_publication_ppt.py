def stat_grid(slide, y, items, h=1.05):
    """Evenly spaced stat cards: gutters computed from the count, so any number
    of cards stays flush with the same left/right margins as everything else."""
    k = len(items)
    gut = 0.22
    w = (SW - 2 * M - gut * (k - 1)) / k
    for i, (big, small) in enumerate(items):
        x = M + i * (w + gut)
        rect(slide, x, y, w, h, LIGHT)
        rect(slide, x, y, w, 0.055, ACC2)
        txbox(slide, x + 0.12, y + 0.16, w - 0.24, 0.46, big, size=23, bold=True,
              color=ACC, align=PP_ALIGN.CENTER)
        txbox(slide, x + 0.10, y + 0.62, w - 0.20, 0.38, small, size=9.5,
              color=GREY, align=PP_ALIGN.CENTER)


