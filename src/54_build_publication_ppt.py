def build_positive_controls():
    """Known drug axes the pipeline recovered blind, across the whole phenome.

    The archival positive-control figure was drawn when the scan covered 13 curated
    endpoints and could therefore only show three axes. Phenome-wide the same ten
    already-drugged genes recover far more endpoints, which is a much stronger
    calibration statement.
    """
    K = NOV[NOV["category_label"] == "recovered known axis"].copy()
    K["nlp"] = -np.log10(K["FDR"].clip(lower=1e-300))
    top = K.sort_values("nlp", ascending=False).head(16).iloc[::-1]

    fig, axes = plt.subplots(1, 2, figsize=(13.2, 5.7),
                             gridspec_kw={"width_ratios": [1.72, 1]})
    ax = axes[0]
    y = np.arange(len(top))
    ax.barh(y, top["nlp"], height=.7,
            color=[RISK if o > 1 else PROT for o in top["OR"]])
    for i, r in enumerate(top.itertuples()):
        bits = [f"OR {r.OR:.2f}"]
        if pd.notna(r.PP_H4):
            bits.append(f"PP.H4 {r.PP_H4:.2f}")
        ax.text(r.nlp + top["nlp"].max() * .015, i, "   ".join(bits),
                va="center", fontsize=7.6, color="#444")
    ax.set_yticks(y)
    ax.set_yticklabels([f"{r.gene_symbol} → {_short(r.disease, 40)}" for r in top.itertuples()],
                       fontsize=8)
    ax.set_xlim(0, top["nlp"].max() * 1.38)
    ax.set_xlabel("evidence, -log10 FDR")
    ax.set_title(f"A · Strongest recovered known drug axes ({len(K)} pairs phenome-wide)",
                 loc="left", fontweight="bold", fontsize=10)
    ax.plot([], [], "s", color=RISK, label="risk-increasing")
    ax.plot([], [], "s", color=PROT, label="protective")
    ax.legend(fontsize=8, loc="lower right")
    _despine(ax)

    ax = axes[1]
    g = K.groupby("gene_symbol").agg(n=("OR", "size"),
                                     nd=("disease_system", "nunique")).sort_values("n")
    y = np.arange(len(g))
    ax.barh(y, g["n"], height=.62, color="#8e8e8e")
    for i, (gene, r) in enumerate(g.iterrows()):
        ax.text(r["n"] + g["n"].max() * .02, i,
                f"{KNOWN_DRUG.get(gene, '')}  ·  {_plural(int(r['nd']), 'disease system')}",
                va="center", fontsize=7.8, color="#444")
    ax.set_yticks(y); ax.set_yticklabels(g.index, fontsize=9)
    ax.set_xlim(0, g["n"].max() * 2.05)
    ax.set_xlabel("endpoints recovered")
    ax.set_title("B · Recovery per already-drugged gene", loc="left",
                 fontweight="bold", fontsize=10)
    _despine(ax)
    fig.tight_layout(w_pad=2.2)
    return _save(fig, "DECK_positive_controls.png")


