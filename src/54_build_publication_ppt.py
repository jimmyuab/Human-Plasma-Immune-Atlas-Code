def build(prs, spec, tag):
    """Figure labels are assigned here rather than stored in the spec: the same spec
    builds both decks and slides get added or removed, so any hard-coded 'Figure 12'
    would go stale the moment the deck changed. A stored label of '#' means 'number me'."""
    n = fignum = 0
    for item in spec:
        n += 1
        if item[0] == "SECTION":
            _, kicker, title, blurb, bullets = item
            section_slide(prs, n, kicker, title, blurb, bullets)
            print(f"  {n:>2}  [section] {title}")
        else:
            sub, fname, label, title, subtitle, cap = item
            fignum += 1
            if label == "#":
                label = f"Figure {fignum}"
            path = F(sub, fname)
            if not os.path.exists(path):
                print(f"  {n:>2}  !! MISSING {sub}/{fname} — slide skipped")
                n -= 1
                fignum -= 1
                continue
            fig_slide(prs, n, tag, label, title, path, cap, subtitle)
            print(f"  {n:>2}  {label:<11} {fname}")
    return n


